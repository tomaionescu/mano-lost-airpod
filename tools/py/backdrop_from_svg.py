"""Write tools/blender/campus_backdrop_data.py: the footprints of the buildings around the campus, read from
docs/campus_layout.svg (OSM / cadastre / IGN outlines in game metres, docs/CAMPUS_LAYOUT.md §1-§3).

usage: python3.11 tools/py/backdrop_from_svg.py
The SVG maps game x to (px - 432) / 4.8 and game z to (py - 533.6) / 4.8 (its 10 m grid). Labelled neighbours
(fill #c9c1b4) keep a name; the Paritalie annexes (#7f9fb5) too; other IGN buildings (#dcd5c9) go to OTHERS,
except those that are campus buildings the level models itself."""
import os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SVG = os.path.join(ROOT, "docs", "campus_layout.svg")
OUT = os.path.join(ROOT, "tools", "blender", "campus_backdrop_data.py")

# bounding-box centre of a labelled polygon -> name (docs/CAMPUS_LAYOUT.md §3.3)
NAMED = [
    ((-40.3, -14.5), "N1317"),        # 13-17 rue Pasteur, 7 storeys, 19.5 m
    ((-56.1, -9.6), "N11"),           # 11 rue Pasteur, 5 storeys, 16.6 m
    ((-56.1, -26.7), "N11_BACK"),
    ((28.5, -18.2), "ARPEJ_W"),       # ARPEJ student residence, 21 rue Pasteur (5 IGN parts), 18.4-24.9 m
    ((39.3, -11.2), "ARPEJ_CORNER"),
    ((38.2, -28.3), "ARPEJ_N"),
    ((32.3, -32.8), "ARPEJ_BACK"),
    ((38.8, -21.0), "ARPEJ_MID"),
    ((34.2, 48.8), "RS29"),           # built by campus_south.salengro_29_31
    ((42.9, 46.8), "RS31"),
    ((64.1, 22.2), "P32"),            # 32 rue Pasteur, 6 storeys, 15.9 m, the Francoise Dolto creche
    ((61.5, 49.6), "P32_SOUTH"),
    ((-60.7, 43.2), "SAL_W1"),
    ((-72.6, 42.8), "SAL_W2"),
    ((85.8, -29.1), "HOTELS"),        # Ibis budget and greet, 20-22 rue Voltaire, 27.2 m
    ((73.7, 1.9), "KIOSK"),
    ((56.2, 24.7), "P32_STUB"),
    ((-37.9, 28.2), "X_PATIO_STUB"),
    ((-50.6, 9.6), "GATE_N"),         # Paritalie gate porches and west annex
    ((-60.5, 11.8), "ANNEX"),
    ((-51.8, 45.8), "GATE_S"),
]
CAMPUS = (-52.0, 48.0, -40.0, 55.0)   # x0, x1, z0, z1: other outlines centred here are modelled by the level


def main():
    s = open(SVG).read()
    X = lambda px: (px - 432.0) / 4.8
    Z = lambda py: (py - 533.6) / 4.8
    named, others = {}, []
    for m in re.finditer(r"<polygon([^>]*)/?>", s):
        a = m.group(1)
        fill = re.search(r'fill="([^"]*)"', a).group(1)
        if fill not in ("#c9c1b4", "#7f9fb5", "#dcd5c9"):
            continue
        pts = [tuple(map(float, p.split(","))) for p in re.search(r'points="([^"]*)"', a).group(1).split()]
        g = [(round(X(x), 1), round(Z(y), 1)) for x, y in pts]
        xs, zs = [p[0] for p in g], [p[1] for p in g]
        cx, cz = (min(xs) + max(xs)) / 2, (min(zs) + max(zs)) / 2
        if fill == "#dcd5c9":
            if CAMPUS[0] < cx < CAMPUS[1] and CAMPUS[2] < cz < CAMPUS[3]:
                continue
            if -190 < cx < 150 and -135 < cz < 125:
                others.append(g)
            continue
        name = min(NAMED, key=lambda e: (e[0][0] - cx) ** 2 + (e[0][1] - cz) ** 2)
        if (name[0][0] - cx) ** 2 + (name[0][1] - cz) ** 2 > 4.0:
            raise SystemExit(f"unnamed neighbour at ({cx:.1f}, {cz:.1f})")
        named[name[1]] = g
    with open(OUT, "w") as f:
        f.write('"""Footprints around the campus in game metres, generated by tools/py/backdrop_from_svg.py from\n'
                'docs/campus_layout.svg (OSM / cadastre / IGN outlines). Do not edit by hand."""\n\n')
        f.write("NAMED = {\n")
        for k in sorted(named):
            f.write(f"    {k!r}: {named[k]!r},\n")
        f.write("}\n\nOTHERS = [\n")
        for g in sorted(others, key=lambda g: (round(g[0][0]), round(g[0][1]))):
            f.write(f"    {g!r},\n")
        f.write("]\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(named)} named, {len(others)} others")


if __name__ == "__main__":
    main()
